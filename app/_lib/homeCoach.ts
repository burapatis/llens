function inputSeed(value: string) {
  return Array.from(value).reduce((total, character, index) => total + character.charCodeAt(0) * (index + 1), 0);
}

function themeScore(input: string, theme: CoachTheme) {
  return theme.keywords.reduce((score, keyword) => score + (input.includes(keyword) ? Math.max(1, keyword.length / 3) : 0), 0);
}

function rotate<T>(items: T[], offset: number) {
  if (!items.length) return items;
  const start = offset % items.length;
  return [...items.slice(start), ...items.slice(0, start)];
}

